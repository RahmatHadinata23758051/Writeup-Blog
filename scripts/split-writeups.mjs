#!/usr/bin/env node
/**
 * split-writeups.mjs
 * 
 * Splits the monolithic src/app/data/writeups.ts into per-event files
 * under src/app/data/writeups/events/.
 * 
 * Usage:
 *   node scripts/split-writeups.mjs
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SRC = join(ROOT, 'src', 'app', 'data');
const EVENTS_DIR = join(SRC, 'writeups', 'events');

// ─── Helpers ────────────────────────────────────────────────────────────────

/** Convert ctfName to a valid TS filename slug */
function toSlug(ctfName) {
  return ctfName
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_|_$/g, '');
}

/** Convert slug to camelCase export name (e.g. "gpnctf_2026" → "gpnctf2026Writeups") */
function toExportName(slug) {
  return slug.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase()) + 'Writeups';
}

/** Serialize a single WriteUp object back to pretty-printed JSON-like TS */
function serializeWriteup(obj, indent = 2) {
  return JSON.stringify(obj, null, indent);
}

// ─── Main ────────────────────────────────────────────────────────────────────

console.log('📂 Reading writeups.ts...');
const raw = readFileSync(join(SRC, 'writeups.ts'), 'utf-8');

// Extract the array content between `writeups: WriteUp[] = [` and the final `];`
const arrayMatch = raw.match(/export const writeups[^=]*=\s*(\[[\s\S]*\]);?\s*$/);
if (!arrayMatch) {
  console.error('❌ Could not find writeups array in writeups.ts');
  process.exit(1);
}

console.log('🔍 Parsing writeups array...');
let writeups;
try {
  writeups = JSON.parse(arrayMatch[1]);
} catch (e) {
  console.error('❌ JSON parse failed:', e.message);
  process.exit(1);
}
console.log(`✅ Parsed ${writeups.length} writeups`);

// Group by ctfName
const byEvent = {};
for (const w of writeups) {
  const name = w.ctfName || 'Unknown';
  if (!byEvent[name]) byEvent[name] = [];
  byEvent[name].push(w);
}

const events = Object.entries(byEvent).sort(([a], [b]) => a.localeCompare(b));
console.log(`\n📊 Found ${events.length} events:`);
events.forEach(([name, list]) => console.log(`   ${name.padEnd(25)} ${list.length} writeups`));

// Create events directory
mkdirSync(EVENTS_DIR, { recursive: true });

// ─── Generate per-event files ─────────────────────────────────────────────

const eventMeta = []; // { slug, exportName, ctfName, count }

for (const [ctfName, list] of events) {
  const slug = toSlug(ctfName);
  const exportName = toExportName(slug);
  eventMeta.push({ slug, exportName, ctfName, count: list.length });

  const filePath = join(EVENTS_DIR, `${slug}.ts`);
  const content = [
    `import type { WriteUp } from '../types';`,
    ``,
    `// ${ctfName} — ${list.length} writeup${list.length > 1 ? 's' : ''}`,
    `export const ${exportName}: WriteUp[] = ${JSON.stringify(list, null, 2)};`,
    ``,
  ].join('\n');

  writeFileSync(filePath, content, 'utf-8');
  console.log(`✅ Written: writeups/events/${slug}.ts  (${list.length} writeups)`);
}

// ─── Generate index.ts ────────────────────────────────────────────────────

const imports = eventMeta
  .map(({ slug, exportName }) => `import { ${exportName} } from './events/${slug}';`)
  .join('\n');

const spread = eventMeta
  .map(({ exportName }) => `  ...${exportName},`)
  .join('\n');

const indexContent = [
  `// Auto-generated by scripts/split-writeups.mjs`,
  `// DO NOT edit manually — add new writeups to the event files in ./events/`,
  ``,
  imports,
  ``,
  `export type { WriteUp, Category, Difficulty, MathFormula, TerminalOutput } from './types';`,
  ``,
  `export const writeups: WriteUp[] = [`,
  spread,
  `];`,
  ``,
].join('\n');

writeFileSync(join(SRC, 'writeups', 'index.ts'), indexContent, 'utf-8');
console.log('\n✅ Written: writeups/index.ts');

// ─── Generate shim ───────────────────────────────────────────────────────

const shimContent = [
  `// Backward-compatibility shim — do not delete`,
  `// The actual data lives in src/app/data/writeups/`,
  `export type { WriteUp, Category, Difficulty, MathFormula, TerminalOutput } from './writeups/types';`,
  `export { writeups } from './writeups/index';`,
  ``,
].join('\n');

writeFileSync(join(SRC, 'writeups.ts'), shimContent, 'utf-8');
console.log('✅ Replaced writeups.ts with backward-compat shim');

console.log('\n🎉 Done! Run `npm run build` to verify.');
